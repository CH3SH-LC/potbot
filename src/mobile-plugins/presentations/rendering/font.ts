/** 空格的前进宽度系数（em）。 */
const SPACE_ADVANCE_FACTOR = 0.4;
/** ASCII 字形单元的前进宽度系数（em）：整格 = 1 em。 */
const ASCII_ADVANCE_FACTOR = 0.62;

function normalizeRows(rows: readonly string[], expected: number): string[] {
  const out: string[] = [];
  for (let i = 0; i < expected; i += 1) {
    const row = rows[i] ?? '';
    out.push(row.padEnd(expected, '.').slice(0, expected));
  }
  return out;
}

/** 把 `#`/`.` 行定义放大到 `outW × outH` 覆盖度位图（最近邻）。 */
function rasterizeRows(
  rows: readonly string[],
  outW: number,
  outH: number,
  font: string,
  substituted: boolean,
  advancePx: number,
): GlyphBitmap {
  const h = rows.length;
  const w = rows[0]?.length ?? 0;
  const coverage = new Uint8Array(outW * outH);
  for (let y = 0; y < outH; y += 1) {
    const sy = Math.min(h - 1, Math.floor((y * h) / outH));
    const row = rows[sy] ?? '';
    for (let x = 0; x < outW; x += 1) {
      const sx = Math.min(w - 1, Math.floor((x * w) / outW));
      if (row[sx] === '#') coverage[y * outW + x] = 255;
    }
  }
  return { widthPx: outW, heightPx: outH, coverage, advancePx, substituted, font };
}

/**
 * 用行字符串（`#`/`.`）构造一个字形位图：按行数等比缩放到高度 `sizePx`（宽度按原横纵比）。
 *
 * 供测试与消费端提供**真实**字形（例如把一份真实汉字的 16×16 点阵喂进来 ⇒ 正方形字形）。
 */
export function bitmapFromGlyphRows(
  rows: readonly string[],
  sizePx: number,
  options?: { readonly font?: string; readonly substituted?: boolean; readonly advancePx?: number },
): GlyphBitmap {
  const font = options?.font ?? BUILTIN_FONT;
  const substituted = options?.substituted ?? false;
  const height = Math.max(1, sizePx);
  const width = rows[0]?.length ?? 8;
  const outW = Math.max(1, Math.round((width * height) / Math.max(1, rows.length)));
  const advancePx = options?.advancePx ?? outW;
  return rasterizeRows(rows, outW, height, font, substituted, advancePx);
}

/** 一个只含若干**真实**字形的固定字形端口（测试 / 消费端注入真字库时用）。 */
export function createFixedGlyphPort(
  glyphs: Readonly<Record<string, readonly string[]>>,
  options?: { readonly font?: string; readonly advancePx?: number },
): GlyphRasterPort {
  const font = options?.font ?? BUILTIN_FONT;
  return {
    hasFont: (requested: string): boolean => requested === font,
    hasGlyph: (requested: string, cp: number): boolean =>
      requested === font && Object.prototype.hasOwnProperty.call(glyphs, String.fromCodePoint(cp)),
    rasterize: ({ font: requested, codePoint, sizePx }): GlyphBitmap | null => {
      if (requested !== font) return null;
      const rows = glyphs[String.fromCodePoint(codePoint)];
      if (rows === undefined) return null;
      return bitmapFromGlyphRows(rows, sizePx, { font, substituted: false, ...(options?.advancePx === undefined ? {} : { advancePx: options.advancePx }) });
    },
  };
}

/**
 * 非 ASCII 的**确定性替代字形**（16×16 基元，按码点生成）。
 *
 * 这是**替代**，不是真实汉字笔形：`substituted: true`，渲染器会如实上报。
 *
 * 导出以便**可注入端口**（`glyph-port.ts`）在真机字形缺字时复用**同一套**确定性替代，
 * 保证「同一码点 ⇒ 同一替代位图」，与内置端口一致。
 */
export function deterministicSubstituteRows(codePoint: number): string[] {
  const rows: string[] = [];
  for (let y = 0; y < 16; y += 1) {
    let row = '';
    for (let x = 0; x < 16; x += 1) {
      let ink = false;
      // 虚线边框（表明"这是一个替代字形格"）。
      if (x === 0 || x === 15) ink = y % 3 !== 0;
      else if (y === 0 || y === 15) ink = x % 3 !== 0;
      else {
        const v1 = (x + y + codePoint) % 4;
        const v2 = (x - y + 16 + (codePoint & 7)) % 6;
        ink = v1 === 0 || v2 === 0;
      }
      row += ink ? '#' : '.';
    }
    rows.push(row);
  }
  return rows;
}

/**
 * 内置字形端口：ASCII 真实字形；非 ASCII 确定性替代字形（`substituted: true`）。
 */
export function createBuiltinGlyphPort(): GlyphRasterPort {
  return {
    hasFont: (requested: string): boolean => requested === BUILTIN_FONT,
    // 本端口对任意码点都能给出**某枚**字形（ASCII 真实 / 其余替代），故 hasGlyph 恒真。
    hasGlyph: (): boolean => true,
    rasterize: ({ font, codePoint, sizePx }): GlyphBitmap | null => {
      if (font !== BUILTIN_FONT) return null;
      const size = Math.max(4, Math.round(sizePx));
      if (codePoint === 0x20) {
        return {
          widthPx: 0,
          heightPx: size,
          coverage: new Uint8Array(0),
          advancePx: Math.round(size * SPACE_ADVANCE_FACTOR),
          substituted: false,
          font,
        };
      }
      const ch = String.fromCodePoint(codePoint);
      const rows = ASCII_8X8[ch];
      if (rows !== undefined) {
        const normalized = rows.split('|');
        const advance = Math.max(2, Math.round(size * ASCII_ADVANCE_FACTOR));
        return rasterizeRows(normalized, advance, size, font, false, advance);
      }
      return rasterizeRows(deterministicSubstituteRows(codePoint), size, size, font, true, size);
    },
  };
}
