/** 把用户原始意图包进用户消息。原样保留，不做润色、不追加事实。 */
export function buildUserPrompt(instruction: string): string {
  return [
    '用户写作要求如下（原样给出，可能不完整）：',
    '<<<',
    instruction,
    '>>>',
    '',
    '请仅按系统消息规定的 JSON 形状输出一个 JSON 对象，不要输出其它任何内容。',
  ].join('\n');
}
