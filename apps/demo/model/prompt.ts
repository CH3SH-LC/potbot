/**
 * S4 —— 提示词。
 *
 * ## 设计取向
 * **越短越好**。本机模型 `thinking` 与正文**共用 `max_tokens`**（已实测），
 * 提示词越长、要求越多，越容易把输出预算推向思考。因此这里只保留
 * 「不写就会出事」的约束，不堆修饰。
 *
 * ## 为什么有「主题忠实」这一节
 * 这是一条**防御性约束，不是对某个已证实缺陷的修复**。
 * 2026-10-02 曾有一份「模型把读书会写成新年贺词」的证据，事后查明那次请求的
 * instruction 在终端里被 GBK / UTF-8 转换搞成乱码，模型拿到的根本不是「读书会」。
 * 用正确 UTF-8 提交时，改动前的提示词产出的标题是「给新生的读书会邀请函」——在题。
 * 也就是说：**模型不守题这个结论不成立**，本节由设计动机支撑（约束"要写对"这一侧），
 * 不由那份被污染的实验支撑。
 *
 * ## 为什么不出现「输出前自检…就重写」
 * 这类祈使句**字面上要求模型在作答前先做一轮自我审议**，与「thinking 和正文共用
 * `max_tokens`」这个既定事实相冲。所以守题要求全部改写成**可直接判定的陈述式规则**：
 * 标题须含核心对象词、不得出现请求未提及的节日/季节/机构/事件。
 * 注意：这条改动同样**不是**由那次 0 输出实验推出的因果（那次实验的输入也是乱码，
 * 结论不可用）；它由上述"共用预算"这一已证事实独立支撑。
 *
 * 传输层另有配套：默认带 `thinking:{type:"disabled"}`（见 transport.ts），
 * 该参数是当前唯一能**确定性**把预算与思考解耦的手段。
 */

